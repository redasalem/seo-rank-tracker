function getScoreColor(score) {
    if (score >= 80) return "#22c55e";
    if (score >= 50) return "#f59e0b";
    return "#ef4444";
}

function getScoreBg(score) {
    if (score >= 80) return "#f0fdf4";
    if (score >= 50) return "#fffbeb";
    return "#fef2f2";
}

function getSeverityStyle(severity) {
    switch (severity) {
        case "critical": return { bg: "#fef2f2", color: "#dc2626", border: "#fecaca" };
        case "warning": return { bg: "#fffbeb", color: "#d97706", border: "#fed7aa" };
        case "info": return { bg: "#eff6ff", color: "#2563eb", border: "#bfdbfe" };
        default: return { bg: "#f9fafb", color: "#6b7280", border: "#e5e7eb" };
    }
}

function buildScoreGaugeSVG(score, size = 120) {
    const strokeWidth = 10;
    const radius = (size - strokeWidth) / 2;
    const circumference = 2 * Math.PI * radius;
    const offset = circumference - (score / 100) * circumference;
    const color = getScoreColor(score);

    return `
        <svg width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
            <circle cx="${size / 2}" cy="${size / 2}" r="${radius}" fill="none" stroke="#e5e7eb" stroke-width="${strokeWidth}" />
            <circle cx="${size / 2}" cy="${size / 2}" r="${radius}" fill="none" stroke="${color}" stroke-width="${strokeWidth}"
                stroke-dasharray="${circumference}" stroke-dashoffset="${offset}" stroke-linecap="round"
                transform="rotate(-90 ${size / 2} ${size / 2})" />
            <text x="${size / 2}" y="${size / 2}" text-anchor="middle" dominant-baseline="central"
                font-size="28" font-weight="bold" fill="${color}">${score}</text>
        </svg>
    `;
}

function escapeHtml(str) {
    if (!str) return "";
    return String(str).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

